def main():
    manifest = tomllib.loads((MOD / "horizon-mixin.toml").read_text())
    body = []
    seen = set()
    for inj in manifest["injection"]:
        target = inj["target"].rsplit("::", 1)[1]
        assert target not in seen, target
        seen.add(target)
        params = TARGETS[target]
        helper = (MOD / inj["helper"]).read_text()
        name = helper.split("fn ", 1)[1].split("(", 1)[0].strip()
        args = ", ".join(b["value"] for b in inj["bindings"])
        # The helper's declared types must be the bindings' (horizon-mixins checks names and types).
        for b in inj["bindings"]:
            assert f'{b["name"]}: {b["ty"]}' in " ".join(helper.split()), (inj["id"], b)
        helper = "\n".join("                " + l if l else "" for l in helper.splitlines())
        body.append(f"            pub(super) fn {target}({params}) {{\n{helper}\n                {name}({args});\n            }}\n")
    (HERE / "src" / "lib.rs").write_text(PRELUDE + "".join(body) + POSTLUDE)
    print(f"{len(seen)} injections")


if __name__ == "__main__":
    main()
